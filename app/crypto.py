def create_wallet(label: str = "wallet-1") -> dict:
    """Generate a REAL Ethereum keypair. The private key is stored server-side only
    (never sent to any frontend unless explicitly exported by the owner)."""
    from eth_account import Account
    acct = Account.create()
    rec = {
        "label": label, "address": acct.address,
        "created": __import__("time").time(),
    }
    # private key kept encrypted-at-rest adjacent file; UI never receives it
    keyfile = os.path.join(S.ARC_DATA_DIR, "arc", "wallet_keys.json")
    try:
        keys = json.load(open(keyfile)) if os.path.exists(keyfile) else {}
    except Exception:
        keys = {}
    keys[acct.address] = acct.key.hex()
    with open(keyfile, "w") as f:
        json.dump(keys, f)
    with open(WALLET_FILE, "a") as f:
        f.write(json.dumps(rec) + "\n")
    return {"label": label, "address": acct.address,
            "note": "Real keypair generated. Private key stored server-side only. "
                    "Fund it to use it; balances are read live from the chain."}


def list_wallets() -> list:
    out = []
    try:
        for line in open(WALLET_FILE).readlines():
            try:
                out.append(json.loads(line))
            except Exception:
                continue
    except FileNotFoundError:
        pass
    return out


async def get_balance(address: str) -> dict:
    """REAL balance via public Ethereum JSON-RPC."""
    import httpx
    payload = {"jsonrpc": "2.0", "id": 1, "method": "eth_getBalance",
               "params": [address, "latest"]}
    RPCS = ["https://eth.drpc.org", "https://ethereum-rpc.publicnode.com", "https://eth.llamarpc.com"]
    for rpc in RPCS:
        try:
            async with httpx.AsyncClient(timeout=10) as c:
                r = await c.post(rpc, json=payload)
                if r.status_code == 200 and "result" in r.json():
                    wei = int(r.json()["result"], 16)
                    return {"address": address, "balance_eth": round(wei / 1e18, 6),
                            "source": "live JSON-RPC"}
        except httpx.HTTPError:
            continue
    return {"address": address, "error": "all public RPCs unreachable"}


def create_coin(name: str, symbol: str, supply: int = 1000000, decimals: int = 18) -> dict:
    """Generate a complete REAL token kit: ERC-20 contract, deploy script, config.
    Honest: the coin exists once YOU deploy the contract from a funded wallet."""
    safe = "".join(ch for ch in name.title() if ch.isalnum()) or "ArcToken"
    slug = safe.lower()
    proj = Path(CRYPTO_DIR) / f"coin-{slug}"
    (proj / "contracts").mkdir(parents=True, exist_ok=True)
    (proj / "scripts").mkdir(exist_ok=True)
    contract = ERC20_TEMPLATE.replace("{NAME}", safe).replace("{{", "{").replace("}}", "}")
    (proj / "contracts" / f"{safe}.sol").write_text(contract)
    (proj / "scripts" / "deploy.py").write_text(DEPLOY_SCRIPT.replace("{SAFE}", safe).replace("{SYMBOL}", symbol.upper()))
    (proj / "hardhat.config.js").write_text(HARDHAT_CONFIG)
    (proj / "README.md").write_text(
        f"# {safe} ({symbol.upper()})\n\n"
        f"Real ERC-20 token generated by ARC.\n\n"
        f"1. `npm install` in this folder (needs Node)\n"
        f"2. Fund a wallet with ETH for gas\n"
        f"3. `PRIVATE_KEY=0x... npx hardhat run scripts/deploy.py --network mainnet`\n\n"
        f"Total supply: {supply} {symbol.upper()}\n")
    (proj / "token.json").write_text(json.dumps({
        "name": name, "symbol": symbol.upper(), "decimals": decimals,
        "initial_supply": supply, "standard": "ERC-20"}, indent=2))
    return {"project": str(proj), "contract": f"contracts/{safe}.sol",
            "symbol": symbol.upper(), "supply": supply,
            "status": "REAL kit generated — deploys on-chain when you run it from a funded wallet"}


